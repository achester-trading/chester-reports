#!/usr/bin/env python3
"""
The dated-appendix queue, one file per entry, and its index written by a tool
(S1 part 4; the cloud-sessions brief, section 2.2).

A builder adds an entry by adding a file, never by editing the queue:

    docs/dated-appendix-queue/<paper-slug>/<date>-<id>.md

where <paper-slug> names the paper or ledger the entry waits for ("unplaced"
when the order names none), <date> is the entry's filing date (YYYY-MM-DD) and
<id> sorts it within that date. The file holds the entry exactly as it should
read, from its "## " heading on. docs/dated-appendix-queue/_preface.md holds the
text above the first entry.

    python tools/appendix_queue_index.py --check    # the index matches the files
    python tools/appendix_queue_index.py --write    # regenerate the index

The index, docs/dated-appendix-queue.md, is a generated-by line, the preface,
then every entry in (date, id) order across all slugs, concatenated byte for
byte. Readers (the batch gates) read queue_text(), the same concatenation, so
they read the directory.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
INDEX = Path("docs") / "dated-appendix-queue.md"
QUEUE = Path("docs") / "dated-appendix-queue"
PREFACE = "_preface.md"
ENTRY_RX = re.compile(r"^(\d{4}-\d{2}-\d{2})-(.+)\.md$")
GENERATED = ("<!-- Generated by tools/appendix_queue_index.py --write from "
             "docs/dated-appendix-queue/: add an entry as a file there; never edit "
             "this index. -->\n")


def _text(p: Path) -> str:
    return p.read_bytes().decode("utf-8").replace("\r\n", "\n")


def entries(root: Path = REPO) -> list[Path]:
    """Every entry file, in (date, id) order across the slugs."""
    q = root / QUEUE
    out = [p for p in q.glob("*/*.md") if ENTRY_RX.match(p.name)]
    bad = [p for p in q.glob("*/*.md") if not ENTRY_RX.match(p.name)]
    if bad:
        raise ValueError(f"entry files not named <date>-<id>.md: "
                         f"{[b.relative_to(root).as_posix() for b in bad]}")
    return sorted(out, key=lambda p: (ENTRY_RX.match(p.name).groups(), p.parent.name))


def queue_text(root: Path = REPO) -> str:
    """The preface and every entry, concatenated: the queue as readers read it."""
    return _text(root / QUEUE / PREFACE) + "".join(_text(p) for p in entries(root))


def index_text(root: Path = REPO) -> str:
    return GENERATED + queue_text(root)


def run(root: Path, write: bool) -> bool:
    """True when the committed index differs from what the tool writes."""
    p = root / INDEX
    raw = p.read_bytes() if p.exists() else b""
    crlf = b"\r\n" in raw
    new = index_text(root)
    differs = raw.decode("utf-8").replace("\r\n", "\n") != new
    if write and differs:
        p.write_bytes((new.replace("\n", "\r\n") if crlf else new).encode("utf-8"))
    return differs


def main(argv=None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(description="the dated-appendix queue's index")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--check", action="store_true")
    g.add_argument("--write", action="store_true")
    ap.add_argument("--root", default=str(REPO))
    a = ap.parse_args(argv)
    differs = run(Path(a.root), a.write)
    n = len(entries(Path(a.root)))
    if a.write:
        print(f"{'wrote' if differs else 'unchanged:'} {INDEX.as_posix()} ({n} entries)")
        return 0
    print(f"{INDEX.as_posix()} matches its {n} entry files" if not differs
          else f"{INDEX.as_posix()} is out of date (run --write)")
    return 1 if differs else 0


if __name__ == "__main__":
    sys.exit(main())
