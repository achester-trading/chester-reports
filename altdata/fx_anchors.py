# ---------------------------------------------------------------------------
# Loader: convert anchor points to pandas Series (decimal-year index -> dates)
# so the chart code has ONE input type whether data is fetched or reconstructed.
# ---------------------------------------------------------------------------
import datetime as _dt

def _decyear_to_date(x: float) -> "_dt.date":
    year = int(x)
    rem = x - year
    # anchors at integer years are year-END values
    if rem == 0:
        return _dt.date(year, 12, 31)
    day = int(rem * 365.25)
    return _dt.date(year, 1, 1) + _dt.timedelta(days=day)

def anchor_series(key: str, panel: str = "long"):
    """Return (dates, values) for an anchor set; panel in {'long','five'}."""
    cfg = ALL[key]
    pts = sorted(cfg[panel]) if panel in cfg else sorted(cfg["long"])
    return [_decyear_to_date(x) for x, _ in pts], [v for _, v in pts]
